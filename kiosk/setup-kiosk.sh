#!/usr/bin/env bash
# RAISE kiosk setup for Raspberry Pi OS with desktop (Bookworm or newer).
#
# Hosted site (works from a pendrive, no repo needed):
#     bash setup-kiosk.sh https://your-site.example/index.html
# Local copy (run from inside the RAISE repo, serves it on localhost):
#     bash kiosk/setup-kiosk.sh
# Then reboot. The Pi boots straight into the self-checkout, full screen.
#
# Run as your normal desktop user (not root); it uses sudo where needed.
#
# What it sets up:
#   1. Hosted mode: nothing to serve. Local mode: a web server (systemd) on localhost:8080.
#      The page must be https or localhost, or the camera and pass crypto won't work.
#   2. A launcher that opens Chromium in kiosk mode, camera permission pre-granted.
#   3. Autostart for whichever desktop the Pi runs (labwc, Wayfire or X11/LXDE).
#   4. Desktop auto-login and no screen blanking.
set -euo pipefail

PORT="${PORT:-8080}"
LAUNCHER="$HOME/.local/bin/raise-kiosk"
URL="${1:-}"

if [ "$(id -u)" -eq 0 ]; then
    echo "Run this as your normal desktop user, not root. It uses sudo where needed." >&2
    exit 1
fi

if [ -n "$URL" ]; then
    MODE=hosted
    case "$URL" in
        https://*|http://localhost*|http://127.0.0.1*) ;;
        http://*) echo "Warning: $URL is not https. Chromium blocks the camera on plain http sites." >&2 ;;
        *) echo "That doesn't look like a URL: $URL (it should start with https://)" >&2; exit 1 ;;
    esac
else
    MODE=local
    APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
    if [ ! -f "$APP_DIR/index.html" ]; then
        echo "No URL given and no RAISE repo next to this script." >&2
        echo "Usage: bash setup-kiosk.sh https://your-site.example/index.html" >&2
        exit 1
    fi
    URL="http://localhost:${PORT}/index.html"
fi
echo "==> Kiosk page ($MODE): $URL"

echo "==> Installing packages"
sudo apt-get update -y
CHROMIUM="$(command -v chromium || command -v chromium-browser || true)"
if [ -z "$CHROMIUM" ]; then
    sudo apt-get install -y chromium || sudo apt-get install -y chromium-browser
    CHROMIUM="$(command -v chromium || command -v chromium-browser)"
fi
sudo apt-get install -y python3 curl
echo "    Chromium: $CHROMIUM"

if [ "$MODE" = "local" ]; then
echo "==> Local web server: raise-kiosk-server.service on port $PORT"
sudo tee /etc/systemd/system/raise-kiosk-server.service >/dev/null <<EOF
[Unit]
Description=RAISE self-checkout static web server
After=network.target

[Service]
User=$USER
WorkingDirectory=$APP_DIR
ExecStart=/usr/bin/python3 -m http.server $PORT --bind 127.0.0.1
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
sudo systemctl daemon-reload
sudo systemctl enable --now raise-kiosk-server.service
fi

echo "==> Kiosk launcher: $LAUNCHER"
mkdir -p "$(dirname "$LAUNCHER")"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Opens the RAISE self-checkout full screen. Generated by kiosk/setup-kiosk.sh.
# Log of every start: ~/.cache/raise-kiosk.log

mkdir -p "\$HOME/.cache"
exec >>"\$HOME/.cache/raise-kiosk.log" 2>&1
echo "=== \$(date) start (session: \${XDG_SESSION_TYPE:-?}, display: \${WAYLAND_DISPLAY:-\${DISPLAY:-none}})"

# Several autostart hooks may call this; only one kiosk may run. The lock is held by
# Chromium itself (exec keeps fd 9 open) until the kiosk closes.
exec 9>"\$HOME/.cache/raise-kiosk.lock"
if ! flock -n 9; then
    echo "kiosk already running, exiting"
    exit 0
fi

# Let the desktop finish starting.
sleep 5

# Wait until the page is reachable (Wi-Fi or the local server can take a while at boot).
for i in \$(seq 1 60); do
    if curl -s -o /dev/null --max-time 3 "$URL"; then echo "page reachable after \${i}s"; break; fi
    sleep 1
done

# After a power cut Chromium shows a "Restore pages?" bubble; mark the last exit as clean.
PREFS="\$HOME/.config/chromium/Default/Preferences"
if [ -f "\$PREFS" ]; then
    sed -i 's/"exited_cleanly":false/"exited_cleanly":true/; s/"exit_type":"[^"]*"/"exit_type":"Normal"/' "\$PREFS"
fi

echo "launching $CHROMIUM"
exec "$CHROMIUM" \\
    --kiosk "$URL" \\
    --ozone-platform-hint=auto \\
    --noerrdialogs \\
    --disable-infobars \\
    --no-first-run \\
    --disable-session-crashed-bubble \\
    --disable-features=Translate,TranslateUI \\
    --check-for-update-interval=31536000 \\
    --use-fake-ui-for-media-stream \\
    --autoplay-policy=no-user-gesture-required \\
    --overscroll-history-navigation=0 \\
    --disable-pinch \\
    --password-store=basic
EOF
chmod +x "$LAUNCHER"

echo "==> Autostart"
# Raspberry Pi OS has shipped three desktops (labwc, Wayfire, X11/LXDE), and some start
# apps from ~/.config/autostart too. Register in every one; the launcher exits if a kiosk
# is already running, so it never opens twice.

# 1. Standard XDG autostart (used by the Pi's session on all three desktops)
mkdir -p "$HOME/.config/autostart"
cat > "$HOME/.config/autostart/raise-kiosk.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=RAISE Kiosk
Exec=$LAUNCHER
X-GNOME-Autostart-enabled=true
EOF
echo "    XDG:     ~/.config/autostart/raise-kiosk.desktop"

# 2. labwc (Raspberry Pi OS default since late 2024)
if command -v labwc >/dev/null 2>&1 || [ -d /etc/xdg/labwc ]; then
    AUTOSTART="$HOME/.config/labwc/autostart"
    mkdir -p "$(dirname "$AUTOSTART")"
    # A user autostart file replaces the system one, so start from a copy of it.
    [ -f "$AUTOSTART" ] || { [ -f /etc/xdg/labwc/autostart ] && cp /etc/xdg/labwc/autostart "$AUTOSTART" || touch "$AUTOSTART"; }
    sed -i '\|raise-kiosk|d' "$AUTOSTART"
    echo "$LAUNCHER &" >> "$AUTOSTART"
    echo "    labwc:   $AUTOSTART"
fi

# 3. Wayfire (Raspberry Pi OS Bookworm, 2023-2024)
if command -v wayfire >/dev/null 2>&1; then
    INI="$HOME/.config/wayfire.ini"
    touch "$INI"
    sed -i '\|raise-kiosk|d' "$INI"
    if grep -q '^\[autostart\]' "$INI"; then
        sed -i "/^\[autostart\]/a raise = $LAUNCHER" "$INI"
    else
        printf '\n[autostart]\nraise = %s\n' "$LAUNCHER" >> "$INI"
    fi
    echo "    Wayfire: $INI"
fi

# 4. X11 / LXDE (older Raspberry Pi OS, or X11 chosen in raspi-config)
if [ -d /etc/xdg/lxsession ] || command -v lxsession >/dev/null 2>&1; then
    AUTOSTART="$HOME/.config/lxsession/LXDE-pi/autostart"
    mkdir -p "$(dirname "$AUTOSTART")"
    [ -f "$AUTOSTART" ] || { [ -f /etc/xdg/lxsession/LXDE-pi/autostart ] && cp /etc/xdg/lxsession/LXDE-pi/autostart "$AUTOSTART" || touch "$AUTOSTART"; }
    sed -i '\|raise-kiosk|d; \|^@xset s off|d; \|^@xset -dpms|d; \|^@xset s noblank|d' "$AUTOSTART"
    cat >> "$AUTOSTART" <<EOF
@xset s off
@xset -dpms
@xset s noblank
@$LAUNCHER
EOF
    echo "    X11:     $AUTOSTART"
fi

echo "==> Desktop auto-login and no screen blanking"
if command -v raspi-config >/dev/null 2>&1; then
    sudo raspi-config nonint do_boot_behaviour B4 || echo "    (could not set auto-login; set it in raspi-config > System > Boot)"
    sudo raspi-config nonint do_blanking 1 || echo "    (could not disable blanking; set it in raspi-config > Display)"
else
    echo "    raspi-config not found: enable desktop auto-login and disable screen blanking manually."
fi

cat <<EOF

Done. Reboot to start the kiosk:   sudo reboot

  Kiosk page:      $URL
  Start it now:    $LAUNCHER &
  Exit kiosk:      Alt+F4
  Boot log:        cat ~/.cache/raise-kiosk.log
  Reload the app:  Ctrl+Shift+R in the kiosk  (or: pkill chromium; $LAUNCHER &)
  Change the URL:  run this script again with the new URL
EOF
